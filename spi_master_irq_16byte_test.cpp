/*
 * ============================================================
 * CM5 SPI Master + GPIO25 Interrupt + 204-byte Data Logging
 * ============================================================
 *
 * Test flow:
 *
 * STM32H755 CM7
 *      |
 *      | PE3 HIGH
 *      v
 * CM5 GPIO25 RISING EDGE
 *      |
 *      v
 * C++ program wakes up
 *      |
 *      v
 * SPI Master transaction
 *      |
 *      +-- CS LOW
 *      +-- SCK generated by CM5
 *      +-- receive 204 bytes
 *      +-- CS HIGH
 *      |
 *      v
 * Sequence verification
 *      |
 *      v
 * Store complete 204-byte packet
 *      |
 *      v
 * Check trajectory complete condition
 *      |
 *      v
 * Write trajectory files
 *
 * IMPORTANT:
 *
 * The SPI transaction is NOT started periodically.
 *
 * GPIO25 RISING event is the ONLY trigger that starts
 * an SPI transaction.
 * ============================================================
 */


/* ------------------------------------------------------------
 * Configuration
 * ------------------------------------------------------------ */

static constexpr const char* GPIO_CHIP = "/dev/gpiochip0";
static constexpr unsigned int GPIO_LINE = 25;
static constexpr const char* GPIO_CONSUMER =
    "spi-master-irq-16byte-test";

static constexpr const char* SPI_DEVICE = "/dev/spidev0.0";

static constexpr uint8_t SPI_MODE = SPI_MODE_0;

/*
 * SPI speed validated during STM32H755 testing.
 */
static constexpr uint32_t SPI_SPEED_HZ = 12000000U;

static constexpr uint8_t SPI_BITS_PER_WORD = 8U;

static constexpr size_t TEST_DATA_SIZE = 204U;


/* ------------------------------------------------------------
 * Trajectory logging configuration
 * ------------------------------------------------------------ */

static constexpr const char* LOG_DIRECTORY = "/srv/ftp/LOG";

static constexpr const char* LATEST_LOG_FILE =
    "/srv/ftp/LOG/trajLog.bin";

static constexpr const char* TRAJECTORY_SOCKET_PATH =
    "/tmp/gmt_trajectory.sock";


/* ------------------------------------------------------------
 * SPI Master
 * ------------------------------------------------------------ */

class SpiMaster
{
public:

    SpiMaster() = default;

    ~SpiMaster()
    {
        Close();
    }

    bool Open()
    {
        fd_ = open(SPI_DEVICE, O_RDWR);

        if (fd_ < 0)
        {
            perror("open SPI device");
            return false;
        }

        uint8_t mode = SPI_MODE;

        if (ioctl(fd_, SPI_IOC_WR_MODE, &mode) < 0)
        {
            perror("SPI_IOC_WR_MODE");
            Close();
            return false;
        }

        uint8_t bits = SPI_BITS_PER_WORD;

        if (ioctl(fd_, SPI_IOC_WR_BITS_PER_WORD, &bits) < 0)
        {
            perror("SPI_IOC_WR_BITS_PER_WORD");
            Close();
            return false;
        }

        uint32_t speed = SPI_SPEED_HZ;

        if (ioctl(fd_, SPI_IOC_WR_MAX_SPEED_HZ, &speed) < 0)
        {
            perror("SPI_IOC_WR_MAX_SPEED_HZ");
            Close();
            return false;
        }

        std::cout
            << "[SPI] Device       : " << SPI_DEVICE << '\n'
            << "[SPI] Mode         : 0\n"
            << "[SPI] Bits         : "
            << static_cast<unsigned int>(bits) << '\n'
            << "[SPI] Speed        : "
            << speed << " Hz\n";

        return true;
    }


    bool Transfer(const uint8_t* tx,
                  uint8_t* rx,
                  size_t length)
    {
        if (fd_ < 0)
        {
            std::cerr << "[SPI] Device is not open\n";
            return false;
        }

        struct spi_ioc_transfer transfer{};

        transfer.tx_buf =
            reinterpret_cast<unsigned long>(tx);

        transfer.rx_buf =
            reinterpret_cast<unsigned long>(rx);

        transfer.len =
            static_cast<uint32_t>(length);

        transfer.speed_hz = SPI_SPEED_HZ;
        transfer.bits_per_word = SPI_BITS_PER_WORD;

        /*
         * delay_usecs = 0
         *
         * CS is controlled by spidev.
         *
         * During this transfer:
         *
         * CS LOW
         *      |
         *      +-- 204 bytes transferred
         *      |
         * CS HIGH
         */
        transfer.delay_usecs = 0;

        int result =
            ioctl(fd_, SPI_IOC_MESSAGE(1), &transfer);

        if (result < 0)
        {
            perror("SPI_IOC_MESSAGE");
            return false;
        }

        if (result != static_cast<int>(length))
        {
            std::cerr
                << "[SPI] Unexpected transfer length: "
                << result
                << " / "
                << length
                << '\n';

            return false;
        }

        return true;
    }


    void Close()
    {
        if (fd_ >= 0)
        {
            close(fd_);
            fd_ = -1;
        }
    }


private:

    int fd_ = -1;
};


/*
 * Save one complete trajectory to latest and archive files.
 * Returns true only when both files are written successfully.
 */
static bool SaveTrajectory(
    const std::vector<uint8_t>& trajectory_buffer)
{
    if (trajectory_buffer.empty())
    {
        std::cerr << "[LOG] Cannot save empty trajectory\n";
        return false;
    }

    const std::time_t current_time = std::time(nullptr);
    std::tm local_time{};

    if (localtime_r(&current_time, &local_time) == nullptr)
    {
        std::cerr << "[LOG] Failed to get local time\n";
        return false;
    }

    std::ostringstream filename_stream;

    filename_stream
        << LOG_DIRECTORY
        << "/trajLog_"
        << std::setfill('0')
        << std::setw(4) << (local_time.tm_year + 1900)
        << "-"
        << std::setw(2) << (local_time.tm_mon + 1)
        << "-"
        << std::setw(2) << local_time.tm_mday
        << "-"
        << std::setw(2) << local_time.tm_hour
        << "-"
        << std::setw(2) << local_time.tm_min
        << "-"
        << std::setw(2) << local_time.tm_sec
        << ".bin";

    const std::string archive_filename = filename_stream.str();

    /*
     * Write latest trajectory.
     */
    std::ofstream latest_file(
        LATEST_LOG_FILE,
        std::ios::binary | std::ios::trunc);

    if (!latest_file)
    {
        std::cerr
            << "[LOG] Failed to open "
            << LATEST_LOG_FILE << '\n';
        return false;
    }

    latest_file.write(
        reinterpret_cast<const char*>(trajectory_buffer.data()),
        static_cast<std::streamsize>(trajectory_buffer.size()));

    latest_file.close();

    if (!latest_file)
    {
        std::cerr
            << "[LOG] Failed to write "
            << LATEST_LOG_FILE << '\n';
        return false;
    }

    /*
     * Write archived trajectory.
     */
    std::ofstream archive_file(
        archive_filename,
        std::ios::binary | std::ios::trunc);

    if (!archive_file)
    {
        std::cerr
            << "[LOG] Failed to open "
            << archive_filename << '\n';
        return false;
    }

    archive_file.write(
        reinterpret_cast<const char*>(trajectory_buffer.data()),
        static_cast<std::streamsize>(trajectory_buffer.size()));

    archive_file.close();

    if (!archive_file)
    {
        std::cerr
            << "[LOG] Failed to write "
            << archive_filename << '\n';
        return false;
    }

    std::cout
        << "[LOG] Trajectory saved"
        << " | packets="
        << (trajectory_buffer.size() / TEST_DATA_SIZE)
        << " | bytes=" << trajectory_buffer.size()
        << '\n';

    std::cout
        << "[LOG] Latest  : "
        << LATEST_LOG_FILE << '\n';

    std::cout
        << "[LOG] Archive : "
        << archive_filename << '\n';

    return true;
}



/* ------------------------------------------------------------
 * Main
 * ------------------------------------------------------------ */

int main()
{
    std::cout
        << "========================================\n"
        << "CM5 SPI Master + GPIO25 Interrupt Test\n"
        << "========================================\n"
        << "GPIO chip : " << GPIO_CHIP << '\n'
        << "GPIO line : " << GPIO_LINE << '\n'
        << "Edge      : RISING\n"
        << "SPI device: " << SPI_DEVICE << '\n'
        << "SPI mode  : 0\n"
        << "SPI speed : " << SPI_SPEED_HZ << " Hz\n"
        << "RX size   : " << TEST_DATA_SIZE << " bytes\n"
        << "Log path  : " << LOG_DIRECTORY << '\n'
        << "Exit      : Press 'q' to exit after the final complete packet is logged\n"
        << "========================================\n";


    /*
     * --------------------------------------------------------
     * Open GPIO chip
     * --------------------------------------------------------
     *
     * libgpiod 2.x C API
     */

    gpiod_chip* gpio_chip = nullptr;
    gpiod_line_request* gpio_request = nullptr;

    gpio_chip = gpiod_chip_open(GPIO_CHIP);

    if (gpio_chip == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to open "
            << GPIO_CHIP
            << '\n';

        return 1;
    }


    /*
     * --------------------------------------------------------
     * Create GPIO line request
     * --------------------------------------------------------
     *
     * GPIO25:
     *
     *   Input
     *   Rising edge detection
     *
     * STM32 PE3:
     *
     *   LOW -> HIGH
     *
     * generates one event.
     */

    gpiod_line_settings* gpio_settings =
        gpiod_line_settings_new();

    if (gpio_settings == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to create line settings\n";

        gpiod_chip_close(gpio_chip);
        return 1;
    }


    if (gpiod_line_settings_set_direction(
            gpio_settings,
            GPIOD_LINE_DIRECTION_INPUT) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 direction\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    if (gpiod_line_settings_set_edge_detection(
            gpio_settings,
            GPIOD_LINE_EDGE_RISING) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 rising edge detection\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Use monotonic timestamps for GPIO events.
     */

    if (gpiod_line_settings_set_event_clock(
            gpio_settings,
            GPIOD_LINE_CLOCK_MONOTONIC) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 event clock\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * GPIO25 offset.
     */

    gpiod_line_config* gpio_config =
        gpiod_line_config_new();

    if (gpio_config == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to create line config\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    unsigned int gpio_offset = GPIO_LINE;

    if (gpiod_line_config_add_line_settings(
            gpio_config,
            &gpio_offset,
            1,
            gpio_settings) < 0)
    {
        std::cerr
            << "[GPIO] Failed to add GPIO25 line settings\n";

        gpiod_line_config_free(gpio_config);
        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Request GPIO25.
     */

    gpio_request =
        gpiod_chip_request_lines(
            gpio_chip,
            nullptr,
            gpio_config);

    if (gpio_request == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to request GPIO25\n";

        gpiod_line_config_free(gpio_config);
        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Settings/configuration objects are no longer needed
     * after the request has been created.
     */

    gpiod_line_config_free(gpio_config);
    gpiod_line_settings_free(gpio_settings);


    /*
     * --------------------------------------------------------
     * Open SPI Master
     * --------------------------------------------------------
     */

    SpiMaster spi;

    if (!spi.Open())
    {
        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * ========================================================
     * >>> Q EXIT SUPPORT <<<
     *
     * Pressing 'q' requests program termination.
     *
     * The program will NOT exit immediately.
     *
     * It must first receive one complete 204-byte packet
     * and create both trajectory files.
     * ========================================================
     */

    struct termios original_terminal{};
    struct termios raw_terminal{};
    bool terminal_modified = false;

    if (isatty(STDIN_FILENO))
    {
        if (tcgetattr(STDIN_FILENO, &original_terminal) == 0)
        {
            raw_terminal = original_terminal;

            raw_terminal.c_lflag &=
                static_cast<unsigned int>(
                    ~(ICANON | ECHO));

            raw_terminal.c_cc[VMIN] = 0;
            raw_terminal.c_cc[VTIME] = 0;

            if (tcsetattr(
                    STDIN_FILENO,
                    TCSANOW,
                    &raw_terminal) == 0)
            {
                terminal_modified = true;
            }
        }
    }

    bool exit_requested = false;
    int trajectory_client_fd = -1;
    std::string socket_command_buffer;


    /*
     * --------------------------------------------------------
     * Trajectory buffer
     * --------------------------------------------------------
     *
     * The trajectory point count is not fixed.
     *
     * Therefore the buffer grows dynamically.
     *
     * Every element added to this buffer is a complete
     * 204-byte SPI packet.
     */

    std::vector<uint8_t> trajectory_buffer;

    /*
     * Initial allocation only.
     *
     * This is NOT a maximum size.
     *
     * vector will automatically grow when necessary.
     */
    trajectory_buffer.reserve(
        TEST_DATA_SIZE * 4096U);


    /*
     * --------------------------------------------------------
     * Expected data
     * --------------------------------------------------------
     */

    std::cout
        << "========================================\n"
        << "Waiting for STM32H755 PE3...\n"
        << "========================================\n";


    uint64_t spi_count = 0;

    uint64_t spi_error_count = 0;
    uint64_t sequence_error_count = 0;
    uint64_t missing_packet_count = 0;
    uint64_t duplicate_packet_count = 0;

    uint16_t expected_sequence = 0U;
    bool have_sequence = false;


    /*
     * ------------------------------------------------------------
     * Periodic statistics
     * ------------------------------------------------------------
     */

    uint64_t last_report_spi_count = 0;
    uint64_t last_report_spi_error_count = 0;
    uint64_t last_report_sequence_error_count = 0;
    uint64_t last_report_missing_packet_count = 0;
    uint64_t last_report_duplicate_packet_count = 0;

    auto last_report_time =
        std::chrono::steady_clock::now();

    constexpr auto STAT_REPORT_INTERVAL =
        std::chrono::seconds(1);


    /*
     * GPIO event file descriptor.
     *
     * poll() waits for either:
     *
     *   GPIO25 rising edge
     *   stdin 'q'
     */

    const int gpio_fd =
        gpiod_line_request_get_fd(gpio_request);

    if (gpio_fd < 0)
    {
        std::cerr
            << "[GPIO] Failed to get GPIO event file descriptor\n";

        if (terminal_modified)
        {
            tcsetattr(
                STDIN_FILENO,
                TCSANOW,
                &original_terminal);
        }

        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Create Unix Domain Socket server.
     */
    const int trajectory_socket_fd =
        socket(AF_UNIX, SOCK_STREAM, 0);

    if (trajectory_socket_fd < 0)
    {
        std::cerr << "[UDS] Failed to create socket\n";
        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }

    struct sockaddr_un socket_address{};
    socket_address.sun_family = AF_UNIX;

    std::strncpy(
        socket_address.sun_path,
        TRAJECTORY_SOCKET_PATH,
        sizeof(socket_address.sun_path) - 1);

    if (bind(
            trajectory_socket_fd,
            reinterpret_cast<const struct sockaddr*>(
                &socket_address),
            sizeof(socket_address)) < 0)
    {
        std::cerr
            << "[UDS] Failed to bind "
            << TRAJECTORY_SOCKET_PATH
            << ": " << std::strerror(errno) << '\n';

        close(trajectory_socket_fd);
        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }

    if (listen(trajectory_socket_fd, 4) < 0)
    {
        std::cerr
            << "[UDS] Failed to listen: "
            << std::strerror(errno) << '\n';

        close(trajectory_socket_fd);
        unlink(TRAJECTORY_SOCKET_PATH);
        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }

    std::cout
        << "[UDS] Listening on "
        << TRAJECTORY_SOCKET_PATH
        << '\n';


    /*
     * --------------------------------------------------------
     * Main event loop
     * --------------------------------------------------------
     *
     * Wait for either:
     *
     *   GPIO25 RISING
     *   keyboard 'q'
     *
     * GPIO25 remains the ONLY trigger for SPI transfer.
     * --------------------------------------------------------
     */

    while (true)
    {
        try
        {
            struct pollfd poll_fds[4]{};

            poll_fds[0].fd = gpio_fd;
            poll_fds[0].events = POLLIN;

            poll_fds[1].fd = STDIN_FILENO;
            poll_fds[1].events = POLLIN;

            poll_fds[2].fd = trajectory_socket_fd;
            poll_fds[2].events = POLLIN;

            poll_fds[3].fd = trajectory_client_fd;
            poll_fds[3].events = POLLIN;

            /*
             * Wait indefinitely for GPIO25 or keyboard input.
             */

            const int poll_result =
                poll(
                    poll_fds,
                    4,
                    -1);

            if (poll_result < 0)
            {
                if (errno == EINTR)
                {
                    continue;
                }

                std::cerr
                    << "[POLL] Failed while waiting for event\n";

                continue;
            }


            /*
             * ------------------------------------------------
             * Check keyboard input.
             * ------------------------------------------------
             */

            if (poll_fds[1].revents & POLLIN)
            {
                char input_char = '\0';

                const ssize_t bytes_read =
                    read(
                        STDIN_FILENO,
                        &input_char,
                        1);

                if (bytes_read == 1 &&
                    (input_char == 'q' ||
                     input_char == 'Q'))
                {
                    if (!exit_requested)
                    {
                        exit_requested = true;

                        std::cout
                            << "\n[EXIT] Exit requested. "
                            << "Waiting for final complete packet...\n";
                    }
                }
            }


            /*
             * ------------------------------------------------
             * GPIO25 event.
             * ------------------------------------------------
             *
             * If GPIO and 'q' arrive together, process GPIO
             * first so that the complete packet is received.
             */

            if (poll_fds[0].revents &
                (POLLIN | POLLPRI))
            {
                gpiod_edge_event_buffer* event_buffer =
                    gpiod_edge_event_buffer_new(1);

                if (event_buffer == nullptr)
                {
                    std::cerr
                        << "[GPIO] Failed to allocate event buffer\n";

                    continue;
                }


                const int num_events =
                    gpiod_line_request_read_edge_events(
                        gpio_request,
                        event_buffer,
                        1);

                if (num_events < 0)
                {
                    std::cerr
                        << "[GPIO] Failed to read GPIO25 event\n";

                    gpiod_edge_event_buffer_free(event_buffer);

                    continue;
                }


                if (num_events == 0)
                {
                    gpiod_edge_event_buffer_free(event_buffer);
                    continue;
                }


                const gpiod_edge_event* event =
                    gpiod_edge_event_buffer_get_event(
                        event_buffer,
                        0);

                if (event == nullptr)
                {
                    std::cerr
                        << "[GPIO] Invalid GPIO25 event\n";

                    gpiod_edge_event_buffer_free(event_buffer);

                    continue;
                }


                /*
                 * RISING edge:
                 *
                 * STM32 PE3 LOW -> HIGH
                 */

                gpiod_edge_event_buffer_free(event_buffer);


                /*
                 * ------------------------------------------------
                 * GPIO interrupt received.
                 *
                 * NOW and ONLY NOW:
                 *
                 * start SPI Master transaction.
                 * ------------------------------------------------
                 */

                uint8_t tx_dummy[TEST_DATA_SIZE]{};
                uint8_t rx_data[TEST_DATA_SIZE]{};

                if (!spi.Transfer(
                        tx_dummy,
                        rx_data,
                        TEST_DATA_SIZE))
                {
                    ++spi_error_count;

                    /*
                     * If q was requested, an incomplete/failed
                     * transfer is NOT sufficient for exit.
                     */
                    continue;
                }


                ++spi_count;


                /*
                 * ------------------------------------------------
                 * Store complete 204-byte packet.
                 * ------------------------------------------------
                 */

                trajectory_buffer.insert(
                    trajectory_buffer.end(),
                    rx_data,
                    rx_data + TEST_DATA_SIZE);


                /*
                 * ------------------------------------------------
                 * Extract 16-bit sequence number.
                 * ------------------------------------------------
                 */

                const uint16_t received_sequence =
                    static_cast<uint16_t>(rx_data[0]) |
                    (static_cast<uint16_t>(rx_data[1]) << 8U);


                /*
                 * ------------------------------------------------
                 * Sequence verification
                 * ------------------------------------------------
                 */

                if (!have_sequence)
                {
                    expected_sequence =
                        static_cast<uint16_t>(
                            received_sequence + 1U);

                    have_sequence = true;
                }
                else
                {
                    if (received_sequence == expected_sequence)
                    {
                        expected_sequence =
                            static_cast<uint16_t>(
                                expected_sequence + 1U);
                    }
                    else
                    {
                        ++sequence_error_count;

                        if (received_sequence >
                            expected_sequence)
                        {
                            const uint16_t missing =
                                static_cast<uint16_t>(
                                    received_sequence -
                                    expected_sequence);

                            missing_packet_count += missing;

                            expected_sequence =
                                static_cast<uint16_t>(
                                    received_sequence + 1U);
                        }
                        else
                        {
                            ++duplicate_packet_count;
                        }
                    }
                }


                /*
                * Save only when q requests final exit.
                * UDS save requests are handled separately.
                */
                const bool final_exit = exit_requested;

                if (final_exit)
                {

                    if (SaveTrajectory(trajectory_buffer))
                    {
                        std::cout
                            << "[EXIT] Final packet logged. "
                            << "Program exiting.\n";

                        break;
                    }

                    /*
                    * Save failed. Keep the buffer and retry
                    * after the next complete SPI packet.
                    */


                }


                /*
                 * ------------------------------------------------------------
                 * Periodic statistics
                 * ------------------------------------------------------------
                 */

                const auto report_now =
                    std::chrono::steady_clock::now();

                if ((report_now - last_report_time) >=
                    STAT_REPORT_INTERVAL)
                {
                    const uint64_t rx_delta =
                        spi_count -
                        last_report_spi_count;

                    const uint64_t spi_error_delta =
                        spi_error_count -
                        last_report_spi_error_count;

                    const uint64_t sequence_error_delta =
                        sequence_error_count -
                        last_report_sequence_error_count;

                    const uint64_t missing_delta =
                        missing_packet_count -
                        last_report_missing_packet_count;

                    const uint64_t duplicate_delta =
                        duplicate_packet_count -
                        last_report_duplicate_packet_count;


                    std::cout
                        << "[1s] "
                        << "RX=" << rx_delta
                        << " SPI_ERR=" << spi_error_delta
                        << " SEQ_ERR=" << sequence_error_delta
                        << " LOST=" << missing_delta
                        << " DUP=" << duplicate_delta
                        << '\n';


                    last_report_spi_error_count =
                        spi_error_count;

                    last_report_spi_count =
                        spi_count;

                    last_report_sequence_error_count =
                        sequence_error_count;

                    last_report_missing_packet_count =
                        missing_packet_count;

                    last_report_duplicate_packet_count =
                        duplicate_packet_count;


                    last_report_time =
                        report_now;
                }
            }


            /*
            * Accept one UDS client.
            */
            if (poll_fds[2].revents & POLLIN)
            {
                const int accepted_fd =
                    accept(trajectory_socket_fd, nullptr, nullptr);

                if (accepted_fd >= 0)
                {
                    if (trajectory_client_fd >= 0)
                    {
                        const char busy_response[] = "SAVE_ERROR\n";

                        send(
                            accepted_fd,
                            busy_response,
                            sizeof(busy_response) - 1,
                            MSG_NOSIGNAL);

                        close(accepted_fd);
                    }
                    else
                    {
                        trajectory_client_fd = accepted_fd;
                        socket_command_buffer.clear();
                    }
                }
            }

            /*
            * Receive a UDS command without blocking GPIO processing.
            */
            if (trajectory_client_fd >= 0 &&
                (poll_fds[3].revents &
                (POLLIN | POLLHUP | POLLERR)))
            {
                bool close_client = false;
                bool command_complete = false;

                if (poll_fds[3].revents & POLLIN)
                {
                    char rx_buffer[64];

                    const ssize_t received =
                        recv(
                            trajectory_client_fd,
                            rx_buffer,
                            sizeof(rx_buffer),
                            MSG_DONTWAIT);

                    if (received > 0)
                    {
                        socket_command_buffer.append(
                            rx_buffer,
                            static_cast<std::size_t>(received));

                        if (socket_command_buffer.size() > 128U)
                        {
                            close_client = true;
                        }
                        else if (socket_command_buffer.find('\n') !=
                                std::string::npos)
                        {
                            command_complete = true;
                        }
                    }
                    else if (received == 0)
                    {
                        close_client = true;
                    }
                    else if (errno != EAGAIN &&
                            errno != EWOULDBLOCK &&
                            errno != EINTR)
                    {
                        close_client = true;
                    }
                }

                if (command_complete)
                {
                    const std::string expected_command =
                        "SAVE_TRAJECTORY\n";

                    const bool valid_command =
                        socket_command_buffer == expected_command;

                    bool save_ok = false;

                    if (valid_command)
                    {
                        save_ok = SaveTrajectory(trajectory_buffer);

                        if (save_ok)
                        {
                            trajectory_buffer.clear();
                        }
                    }

                    const char* response =
                        save_ok ? "SAVE_OK\n" : "SAVE_ERROR\n";

                    const std::size_t response_length =
                        std::strlen(response);

                    send(
                        trajectory_client_fd,
                        response,
                        response_length,
                        MSG_NOSIGNAL);

                    close_client = true;
                }

                if (poll_fds[3].revents & (POLLHUP | POLLERR))
                {
                    close_client = true;
                }

                if (close_client)
                {
                    close(trajectory_client_fd);
                    trajectory_client_fd = -1;
                    socket_command_buffer.clear();
                }
            }

        }
        catch (const std::exception& e)
        {
            std::cerr
                << "[ERROR] "
                << e.what()
                << '\n';
        }
    }


    /*
     * Restore terminal settings before exiting.
     */

    if (terminal_modified)
    {
        tcsetattr(
            STDIN_FILENO,
            TCSANOW,
            &original_terminal);
    }

    /*
     * Close UDS client socket.
     */
    if (trajectory_client_fd >= 0)
    {
        close(trajectory_client_fd);
        trajectory_client_fd = -1;
    }

    close(trajectory_socket_fd);
    unlink(TRAJECTORY_SOCKET_PATH);

    gpiod_line_request_release(gpio_request);
    gpiod_chip_close(gpio_chip);

    return 0;
}

