#include <gpiod.h>
#include <linux/spi/spidev.h>

#include <chrono>
#include <cstdint>
#include <cstring>
#include <ctime>
#include <fcntl.h>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <string>
#include <sys/ioctl.h>
#include <unistd.h>
#include <vector>

/*
 * ============================================================
 * CM5 SPI Master + GPIO25 Interrupt + 204-byte Data Logging
 * ============================================================
 *
 * Test flow:
 *
 * STM32H755 CM7
 *      |
 *      | PE3 HIGH
 *      v
 * CM5 GPIO25 RISING EDGE
 *      |
 *      v
 * C++ program wakes up
 *      |
 *      v
 * SPI Master transaction
 *      |
 *      +-- CS LOW
 *      +-- SCK generated by CM5
 *      +-- receive 204 bytes
 *      +-- CS HIGH
 *      |
 *      v
 * Sequence verification
 *      |
 *      v
 * Store complete 204-byte packet
 *      |
 *      v
 * Check trajectory complete condition
 *      |
 *      v
 * Write trajectory files
 *
 * IMPORTANT:
 *
 * The SPI transaction is NOT started periodically.
 *
 * GPIO25 RISING event is the ONLY trigger that starts
 * an SPI transaction.
 * ============================================================
 */


/* ------------------------------------------------------------
 * Configuration
 * ------------------------------------------------------------ */

static constexpr const char* GPIO_CHIP = "/dev/gpiochip0";
static constexpr unsigned int GPIO_LINE = 25;
static constexpr const char* GPIO_CONSUMER =
    "spi-master-irq-16byte-test";

static constexpr const char* SPI_DEVICE = "/dev/spidev0.0";

static constexpr uint8_t SPI_MODE = SPI_MODE_0;

/*
 * SPI speed validated during STM32H755 testing.
 */
static constexpr uint32_t SPI_SPEED_HZ = 12000000U;

static constexpr uint8_t SPI_BITS_PER_WORD = 8U;

static constexpr size_t TEST_DATA_SIZE = 204U;


/* ------------------------------------------------------------
 * Trajectory logging configuration
 * ------------------------------------------------------------ */

static constexpr const char* LOG_DIRECTORY = "/srv/ftp/LOG";

static constexpr const char* LATEST_LOG_FILE =
    "/srv/ftp/LOG/trajLog.bin";


/*
 * ============================================================
 * >>> TRAJECTORY COMPLETE CONDITION <<<
 *
 * CURRENT TEST CONDITION:
 *
 *     Every 4 seconds, the currently collected trajectory
 *     is considered complete.
 *
 * FUTURE:
 *
 *     Replace this condition with DONE command detection.
 *
 * IMPORTANT:
 *
 *     The condition is checked ONLY AFTER one complete
 *     204-byte SPI packet has been received.
 *
 *     Therefore a packet being transferred when the
 *     4-second boundary occurs will always be completed
 *     before file creation starts.
 * ============================================================
 */
static constexpr auto TRAJECTORY_INTERVAL =
    std::chrono::seconds(4);


/* ------------------------------------------------------------
 * SPI Master
 * ------------------------------------------------------------ */

class SpiMaster
{
public:

    SpiMaster() = default;

    ~SpiMaster()
    {
        Close();
    }

    bool Open()
    {
        fd_ = open(SPI_DEVICE, O_RDWR);

        if (fd_ < 0)
        {
            perror("open SPI device");
            return false;
        }

        uint8_t mode = SPI_MODE;

        if (ioctl(fd_, SPI_IOC_WR_MODE, &mode) < 0)
        {
            perror("SPI_IOC_WR_MODE");
            Close();
            return false;
        }

        uint8_t bits = SPI_BITS_PER_WORD;

        if (ioctl(fd_, SPI_IOC_WR_BITS_PER_WORD, &bits) < 0)
        {
            perror("SPI_IOC_WR_BITS_PER_WORD");
            Close();
            return false;
        }

        uint32_t speed = SPI_SPEED_HZ;

        if (ioctl(fd_, SPI_IOC_WR_MAX_SPEED_HZ, &speed) < 0)
        {
            perror("SPI_IOC_WR_MAX_SPEED_HZ");
            Close();
            return false;
        }

        std::cout
            << "[SPI] Device       : " << SPI_DEVICE << '\n'
            << "[SPI] Mode         : 0\n"
            << "[SPI] Bits         : "
            << static_cast<unsigned int>(bits) << '\n'
            << "[SPI] Speed        : "
            << speed << " Hz\n";

        return true;
    }


    bool Transfer(const uint8_t* tx,
                  uint8_t* rx,
                  size_t length)
    {
        if (fd_ < 0)
        {
            std::cerr << "[SPI] Device is not open\n";
            return false;
        }

        struct spi_ioc_transfer transfer{};

        transfer.tx_buf =
            reinterpret_cast<unsigned long>(tx);

        transfer.rx_buf =
            reinterpret_cast<unsigned long>(rx);

        transfer.len =
            static_cast<uint32_t>(length);

        transfer.speed_hz = SPI_SPEED_HZ;
        transfer.bits_per_word = SPI_BITS_PER_WORD;

        /*
         * delay_usecs = 0
         *
         * CS is controlled by spidev.
         *
         * During this transfer:
         *
         * CS LOW
         *      |
         *      +-- 204 bytes transferred
         *      |
         * CS HIGH
         */
        transfer.delay_usecs = 0;

        int result =
            ioctl(fd_, SPI_IOC_MESSAGE(1), &transfer);

        if (result < 0)
        {
            perror("SPI_IOC_MESSAGE");
            return false;
        }

        if (result != static_cast<int>(length))
        {
            std::cerr
                << "[SPI] Unexpected transfer length: "
                << result
                << " / "
                << length
                << '\n';

            return false;
        }

        return true;
    }


    void Close()
    {
        if (fd_ >= 0)
        {
            close(fd_);
            fd_ = -1;
        }
    }


private:

    int fd_ = -1;
};


/* ------------------------------------------------------------
 * Main
 * ------------------------------------------------------------ */

int main()
{
    std::cout
        << "========================================\n"
        << "CM5 SPI Master + GPIO25 Interrupt Test\n"
        << "========================================\n"
        << "GPIO chip : " << GPIO_CHIP << '\n'
        << "GPIO line : " << GPIO_LINE << '\n'
        << "Edge      : RISING\n"
        << "SPI device: " << SPI_DEVICE << '\n'
        << "SPI mode  : 0\n"
        << "SPI speed : " << SPI_SPEED_HZ << " Hz\n"
        << "RX size   : " << TEST_DATA_SIZE << " bytes\n"
        << "Log path  : " << LOG_DIRECTORY << '\n'
        << "========================================\n";


    /*
     * --------------------------------------------------------
     * Open GPIO chip
     * --------------------------------------------------------
     *
     * libgpiod 2.x C API
     */

    gpiod_chip* gpio_chip = nullptr;
    gpiod_line_request* gpio_request = nullptr;

    gpio_chip = gpiod_chip_open(GPIO_CHIP);

    if (gpio_chip == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to open "
            << GPIO_CHIP
            << '\n';

        return 1;
    }


    /*
     * --------------------------------------------------------
     * Create GPIO line request
     * --------------------------------------------------------
     *
     * GPIO25:
     *
     *   Input
     *   Rising edge detection
     *
     * STM32 PE3:
     *
     *   LOW -> HIGH
     *
     * generates one event.
     */

    gpiod_line_settings* gpio_settings =
        gpiod_line_settings_new();

    if (gpio_settings == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to create line settings\n";

        gpiod_chip_close(gpio_chip);
        return 1;
    }


    if (gpiod_line_settings_set_direction(
            gpio_settings,
            GPIOD_LINE_DIRECTION_INPUT) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 direction\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    if (gpiod_line_settings_set_edge_detection(
            gpio_settings,
            GPIOD_LINE_EDGE_RISING) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 rising edge detection\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Use monotonic timestamps for GPIO events.
     */

    if (gpiod_line_settings_set_event_clock(
            gpio_settings,
            GPIOD_LINE_CLOCK_MONOTONIC) < 0)
    {
        std::cerr
            << "[GPIO] Failed to set GPIO25 event clock\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * GPIO25 offset.
     */

    gpiod_line_config* gpio_config =
        gpiod_line_config_new();

    if (gpio_config == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to create line config\n";

        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    unsigned int gpio_offset = GPIO_LINE;

    if (gpiod_line_config_add_line_settings(
            gpio_config,
            &gpio_offset,
            1,
            gpio_settings) < 0)
    {
        std::cerr
            << "[GPIO] Failed to add GPIO25 line settings\n";

        gpiod_line_config_free(gpio_config);
        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Request GPIO25.
     */

    gpio_request =
        gpiod_chip_request_lines(
            gpio_chip,
            nullptr,
            gpio_config);

    if (gpio_request == nullptr)
    {
        std::cerr
            << "[GPIO] Failed to request GPIO25\n";

        gpiod_line_config_free(gpio_config);
        gpiod_line_settings_free(gpio_settings);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * Settings/configuration objects are no longer needed
     * after the request has been created.
     */

    gpiod_line_config_free(gpio_config);
    gpiod_line_settings_free(gpio_settings);


    /*
     * --------------------------------------------------------
     * Open SPI Master
     * --------------------------------------------------------
     */

    SpiMaster spi;

    if (!spi.Open())
    {
        gpiod_line_request_release(gpio_request);
        gpiod_chip_close(gpio_chip);
        return 1;
    }


    /*
     * --------------------------------------------------------
     * Trajectory buffer
     * --------------------------------------------------------
     *
     * The trajectory point count is not fixed.
     *
     * Therefore the buffer grows dynamically.
     *
     * Every element added to this buffer is a complete
     * 204-byte SPI packet.
     */

    std::vector<uint8_t> trajectory_buffer;

    /*
     * Initial allocation only.
     *
     * This is NOT a maximum size.
     *
     * vector will automatically grow when necessary.
     */
    trajectory_buffer.reserve(
        TEST_DATA_SIZE * 4096U);


    /*
     * Start timing for the current trajectory.
     *
     * The first trajectory starts when the CM5 program
     * reaches the event-processing stage.
     */

    auto trajectory_start_time =
        std::chrono::steady_clock::now();


    /*
     * --------------------------------------------------------
     * Expected data
     * --------------------------------------------------------
     */

    std::cout
        << "========================================\n"
        << "Waiting for STM32H755 PE3...\n"
        << "========================================\n";


    uint64_t spi_count = 0;

    uint64_t spi_error_count = 0;
    uint64_t sequence_error_count = 0;
    uint64_t missing_packet_count = 0;
    uint64_t duplicate_packet_count = 0;

    uint16_t expected_sequence = 0U;
    bool have_sequence = false;


    /*
     * ------------------------------------------------------------
     * Periodic statistics
     * ------------------------------------------------------------
     *
     * Normal packet processing does NOT print to terminal.
     *
     * Statistics are printed once per second so that terminal I/O
     * does not interfere with the 1 ms SPI test.
     */

    uint64_t last_report_spi_count = 0;
    uint64_t last_report_spi_error_count = 0;
    uint64_t last_report_sequence_error_count = 0;
    uint64_t last_report_missing_packet_count = 0;
    uint64_t last_report_duplicate_packet_count = 0;

    auto last_report_time =
        std::chrono::steady_clock::now();

    constexpr auto STAT_REPORT_INTERVAL =
        std::chrono::seconds(1);


    /*
     * --------------------------------------------------------
     * Main event loop
     * --------------------------------------------------------
     *
     * NOTHING happens here until GPIO25 RISING.
     * --------------------------------------------------------
     */

    while (true)
    {
        try
        {
            /*
             * ------------------------------------------------
             * Block until GPIO25 produces an edge event.
             * ------------------------------------------------
             *
             * No GPIO polling.
             *
             * The program sleeps here until STM32 PE3
             * changes LOW -> HIGH.
             */

            if (gpiod_line_request_wait_edge_events(
                    gpio_request,
                    -1) < 0)
            {
                std::cerr
                    << "[GPIO] Failed while waiting for GPIO25 event\n";

                continue;
            }


            /*
             * Read the pending GPIO event.
             */

            gpiod_edge_event_buffer* event_buffer =
                gpiod_edge_event_buffer_new(1);

            if (event_buffer == nullptr)
            {
                std::cerr
                    << "[GPIO] Failed to allocate event buffer\n";

                continue;
            }


            int num_events =
                gpiod_line_request_read_edge_events(
                    gpio_request,
                    event_buffer,
                    1);

            if (num_events < 0)
            {
                std::cerr
                    << "[GPIO] Failed to read GPIO25 event\n";

                gpiod_edge_event_buffer_free(event_buffer);

                continue;
            }


            if (num_events == 0)
            {
                gpiod_edge_event_buffer_free(event_buffer);
                continue;
            }


            const gpiod_edge_event* event =
                gpiod_edge_event_buffer_get_event(
                    event_buffer,
                    0);

            if (event == nullptr)
            {
                std::cerr
                    << "[GPIO] Invalid GPIO25 event\n";

                gpiod_edge_event_buffer_free(event_buffer);

                continue;
            }


            /*
             * We requested RISING edge only,
             * therefore this event is the STM32 PE3
             * LOW -> HIGH notification.
             */

            gpiod_edge_event_buffer_free(event_buffer);


            /*
             * ------------------------------------------------
             * GPIO interrupt received.
             *
             * NOW and ONLY NOW:
             *
             * start SPI Master transaction.
             * ------------------------------------------------
             */

            uint8_t tx_dummy[TEST_DATA_SIZE]{};
            uint8_t rx_data[TEST_DATA_SIZE]{};

            if (!spi.Transfer(
                    tx_dummy,
                    rx_data,
                    TEST_DATA_SIZE))
            {
                ++spi_error_count;

                continue;
            }


            ++spi_count;


            /*
             * ------------------------------------------------
             * Store complete 204-byte packet.
             * ------------------------------------------------
             *
             * This is done only after the SPI transaction
             * has completed successfully.
             */

            trajectory_buffer.insert(
                trajectory_buffer.end(),
                rx_data,
                rx_data + TEST_DATA_SIZE);


            /*
             * ------------------------------------------------
             * Extract 16-bit sequence number.
             * ------------------------------------------------
             *
             * Byte 0 = LSB
             * Byte 1 = MSB
             */

            const uint16_t received_sequence =
                static_cast<uint16_t>(rx_data[0]) |
                (static_cast<uint16_t>(rx_data[1]) << 8U);


            /*
             * ------------------------------------------------
             * Sequence verification
             * ------------------------------------------------
             */

            if (!have_sequence)
            {
                /*
                 * First successfully received packet.
                 *
                 * Accept its sequence as the starting point.
                 */

                expected_sequence =
                    static_cast<uint16_t>(received_sequence + 1U);

                have_sequence = true;
            }
            else
            {
                if (received_sequence == expected_sequence)
                {
                    /*
                     * Correct next packet.
                     */

                    expected_sequence =
                        static_cast<uint16_t>(expected_sequence + 1U);
                }
                else
                {
                    ++sequence_error_count;

                    /*
                     * Forward jump:
                     *
                     * received > expected
                     *
                     * means packets were skipped.
                     */

                    if (received_sequence > expected_sequence)
                    {
                        const uint16_t missing =
                            static_cast<uint16_t>(
                                received_sequence - expected_sequence);

                        missing_packet_count += missing;


                        /*
                         * Continue from the packet after the
                         * received sequence.
                         */

                        expected_sequence =
                            static_cast<uint16_t>(
                                received_sequence + 1U);
                    }
                    else
                    {
                        /*
                         * received < expected.
                         *
                         * This may indicate duplicate or
                         * out-of-order data.
                         */

                        ++duplicate_packet_count;
                    }
                }
            }


            /*
             * ========================================================
             * >>> TRAJECTORY COMPLETE CONDITION <<<
             *
             * CURRENT TEST:
             *
             *     4 seconds elapsed.
             *
             * FUTURE:
             *
             *     Replace ONLY this condition with DONE command
             *     detection.
             *
             * IMPORTANT:
             *
             *     This check is performed AFTER the complete
             *     204-byte SPI transaction and after the packet
             *     has been stored.
             * ========================================================
             */

            const auto trajectory_now =
                std::chrono::steady_clock::now();

            if ((trajectory_now - trajectory_start_time) >=
                TRAJECTORY_INTERVAL)
            {
                /*
                 * ------------------------------------------------
                 * Create timestamp for archived trajectory file.
                 * ------------------------------------------------
                 */

                const std::time_t current_time =
                    std::time(nullptr);

                std::tm local_time{};

                if (localtime_r(
                        &current_time,
                        &local_time) == nullptr)
                {
                    std::cerr
                        << "[LOG] Failed to get local time\n";

                    continue;
                }


                std::ostringstream filename_stream;

                filename_stream
                    << LOG_DIRECTORY
                    << "/trajLog_"
                    << std::setfill('0')
                    << std::setw(4)
                    << (local_time.tm_year + 1900)
                    << "-"
                    << std::setw(2)
                    << (local_time.tm_mon + 1)
                    << "-"
                    << std::setw(2)
                    << local_time.tm_mday
                    << "-"
                    << std::setw(2)
                    << local_time.tm_hour
                    << "-"
                    << std::setw(2)
                    << local_time.tm_min
                    << "-"
                    << std::setw(2)
                    << local_time.tm_sec
                    << ".bin";


                const std::string archive_filename =
                    filename_stream.str();


                /*
                 * ------------------------------------------------
                 * Write latest trajectory.
                 *
                 * trajLog.bin is always overwritten.
                 * ------------------------------------------------
                 */

                std::ofstream latest_file(
                    LATEST_LOG_FILE,
                    std::ios::binary |
                    std::ios::trunc);

                if (!latest_file)
                {
                    std::cerr
                        << "[LOG] Failed to open "
                        << LATEST_LOG_FILE
                        << '\n';

                    continue;
                }


                latest_file.write(
                    reinterpret_cast<const char*>(
                        trajectory_buffer.data()),
                    static_cast<std::streamsize>(
                        trajectory_buffer.size()));


                if (!latest_file)
                {
                    std::cerr
                        << "[LOG] Failed to write "
                        << LATEST_LOG_FILE
                        << '\n';

                    continue;
                }


                latest_file.close();


                /*
                 * ------------------------------------------------
                 * Write archived trajectory.
                 *
                 * This file is never overwritten by the program
                 * unless the exact same timestamp occurs.
                 * ------------------------------------------------
                 */

                std::ofstream archive_file(
                    archive_filename,
                    std::ios::binary |
                    std::ios::trunc);

                if (!archive_file)
                {
                    std::cerr
                        << "[LOG] Failed to open "
                        << archive_filename
                        << '\n';

                    continue;
                }


                archive_file.write(
                    reinterpret_cast<const char*>(
                        trajectory_buffer.data()),
                    static_cast<std::streamsize>(
                        trajectory_buffer.size()));


                if (!archive_file)
                {
                    std::cerr
                        << "[LOG] Failed to write "
                        << archive_filename
                        << '\n';

                    continue;
                }


                archive_file.close();


                /*
                 * ------------------------------------------------
                 * File creation completed successfully.
                 * ------------------------------------------------
                 */

                std::cout
                    << "[LOG] Trajectory complete"
                    << " | packets="
                    << (trajectory_buffer.size() /
                        TEST_DATA_SIZE)
                    << " | bytes="
                    << trajectory_buffer.size()
                    << '\n';

                std::cout
                    << "[LOG] Latest   : "
                    << LATEST_LOG_FILE
                    << '\n';

                std::cout
                    << "[LOG] Archive  : "
                    << archive_filename
                    << '\n';


                /*
                 * Start collecting the next trajectory.
                 */

                trajectory_buffer.clear();

                trajectory_start_time =
                    std::chrono::steady_clock::now();
            }


            /*
             * ------------------------------------------------------------
             * Periodic statistics
             * ------------------------------------------------------------
             *
             * Print statistics once per second.
             *
             * IMPORTANT:
             *
             * Do NOT print one line for every SPI transaction.
             * The target test rate is 1 packet/ms = 1000 packets/sec.
             *
             * Excessive terminal output can affect userspace timing and
             * make the test result less representative of the actual
             * GPIO -> SPI path.
             */

            const auto report_now =
                std::chrono::steady_clock::now();

            if ((report_now - last_report_time) >=
                STAT_REPORT_INTERVAL)
            {
                const uint64_t rx_delta =
                    spi_count - last_report_spi_count;

                const uint64_t spi_error_delta =
                    spi_error_count -
                    last_report_spi_error_count;

                const uint64_t sequence_error_delta =
                    sequence_error_count -
                    last_report_sequence_error_count;

                const uint64_t missing_delta =
                    missing_packet_count -
                    last_report_missing_packet_count;

                const uint64_t duplicate_delta =
                    duplicate_packet_count -
                    last_report_duplicate_packet_count;


                std::cout
                    << "[1s] "
                    << "RX=" << rx_delta
                    << " SPI_ERR=" << spi_error_delta
                    << " SEQ_ERR=" << sequence_error_delta
                    << " LOST=" << missing_delta
                    << " DUP=" << duplicate_delta
                    << '\n';


                last_report_spi_error_count =
                    spi_error_count;

                last_report_spi_count =
                    spi_count;

                last_report_sequence_error_count =
                    sequence_error_count;

                last_report_missing_packet_count =
                    missing_packet_count;

                last_report_duplicate_packet_count =
                    duplicate_packet_count;


                last_report_time =
                    report_now;
            }
        }
        catch (const std::exception& e)
        {
            std::cerr
                << "[ERROR] "
                << e.what()
                << '\n';
        }
    }


    gpiod_line_request_release(gpio_request);
    gpiod_chip_close(gpio_chip);

    return 0;
}